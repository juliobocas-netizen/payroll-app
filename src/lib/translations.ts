export function t(locale: Locale | string, key: string): string {
  return messages[key]?.[locale as Locale] ?? messages[key]?.es ?? key;
}

export function getDateLocale(locale: Locale | string): string {
  return locale === "en" ? "en-US" : "es-PA";
}

export function getCurrencyLocale(locale: Locale | string): string {
  return locale === "en" ? "en-US" : "es-PA";
}

export function formatCurrencyByLocale(
  amount: number,
  locale: Locale | string
): string {
  return new Intl.NumberFormat(getCurrencyLocale(locale), {
    style: "currency",
    currency: "USD",
  }).format(amount);
}

export function formatDateByLocale(
  date: Date | string,
  locale: Locale | string,
  options?: Intl.DateTimeFormatOptions
): string {
  const d = typeof date === "string" ? new Date(date) : date;
  return d.toLocaleDateString(getDateLocale(locale), options);
}

export function formatDateTimeByLocale(
  date: Date | string,
  locale: Locale | string,
  options?: Intl.DateTimeFormatOptions
): string {
  const d = typeof date === "string" ? new Date(date) : date;
  return d.toLocaleString(getDateLocale(locale), options);
}
